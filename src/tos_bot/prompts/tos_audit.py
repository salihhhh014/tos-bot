def _lang_line(lang: str) -> str:
    if lang == "doc":
        return "\nЯзык ответа — язык документа. Термины не переводи, приводи как есть."
    return "\nЯзык ответа — русский."


def build_full_prompt(document: str, lang: str = "ru") -> str:
    # документ кладем как есть, без пересказа — иначе привнесем свои искажения
    return (
        f"<document>\n{document.strip()}\n</document>\n\n"
        f"Разбери по формату из системной инструкции.{_lang_line(lang)}"
    )


def build_extract_prompt(document: str, topic: str, lang: str = "ru") -> str:
    # дословная цитата про тему. ответ либо цитата, либо ровно "НЕТ"
    return (
        f"Найди в документе фрагмент про: {topic.strip()}\n\n"
        f"<document>\n{document.strip()}\n</document>\n\n"
        "Верни ТОЛЬКО дословную цитату из документа (до 800 символов), "
        "без пересказа, без комментариев, без оформления.\n"
        "Если про это в документе ничего нет — верни ровно одно слово: НЕТ\n"
        "Не додумывай и не перефразируй."
        f"{_lang_line(lang)}"
    )
